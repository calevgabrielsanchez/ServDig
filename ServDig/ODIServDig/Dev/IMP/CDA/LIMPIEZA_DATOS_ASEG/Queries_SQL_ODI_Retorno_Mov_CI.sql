--- COMANDO: UPDATE_REF_OBS

UPDATE DIT_BIT_FLUJO_ARCH_MOVCICDA t1
SET REF_OBSERVACION = (
            SELECT LISTAGG(bit2.REF_OBSERVACION, chr(10)) WITHIN GROUP (ORDER BY bit2.REF_OBSERVACION) "REF_OBSERVACION"
            from DIT_BITACORA_PROC_MOVCI_CDA bit2 
            where (trunc(bit2.FEC_REGISTRO_ALTA) = trunc(sysdate) or trunc(bit2.FEC_REGISTRO_ACTUALIZADO) = trunc(sysdate))
            and bit2.IDENTIF_ERROR <> '000'
            and bit2.CVE_ID_TRAMITE = t1.CVE_ID_TRAMITE
          ) , FEC_REGISTRO_ACTUALIZADO = SYSDATE 
where (trunc(t1.FEC_REGISTRO_ALTA) = trunc(sysdate) or trunc(T1.FEC_REGISTRO_ACTUALIZADO) = trunc(sysdate))
and exists (
            select bit2.rowid
            from DIT_BITACORA_PROC_MOVCI_CDA bit2 
            where (trunc(bit2.FEC_REGISTRO_ALTA) = trunc(sysdate) or trunc(bit2.FEC_REGISTRO_ACTUALIZADO) = trunc(sysdate))
            and bit2.IDENTIF_ERROR <> '000'
            and bit2.CVE_ID_TRAMITE = t1.CVE_ID_TRAMITE)

--- COMANDO: UPDATE VALIDA ESTADO

UPDATE DIT_BIT_FLUJO_ARCH_MOVCICDA T1
SET (T1.IND_VALIDA,T1.REF_ESTADO_SOLICITUD,T1.REF_ESTADO_TRAMITE) =
(
SELECT 
CASE WHEN SUM(NVL(IND_CIZ1,2)+ NVL(IND_CIZ2,2)+ NVL(IND_CIZ3,2) + NVL(IND_HC,2)) = 6 THEN 1
     WHEN SUM(NVL(IND_CIZ1,2)+ NVL(IND_CIZ2,2)+ NVL(IND_CIZ3,2) + NVL(IND_HC,2)) = 7 THEN 1
      ELSE null
END IND_VALIDA,
CASE WHEN SUM(NVL(IND_CIZ1,0)+ NVL(IND_CIZ2,0)+ NVL(IND_CIZ3,0) + NVL(IND_HC,0)) = 1 THEN 5
ELSE 5
END REF_ESTADO_SOLICITUD,
CASE WHEN SUM (NVL(IND_CIZ1,0)+ NVL(IND_CIZ2,0)+ NVL(IND_CIZ3,0) + NVL(IND_HC,0)) = 1 THEN 88
ELSE 85
END REF_ESTADO_TRAMITE
FROM DIT_BIT_FLUJO_ARCH_MOVCICDA T2
WHERE T1.CVE_ID_TRAMITE=T2.CVE_ID_TRAMITE
AND (TRUNC(T2.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE) or TRUNC(T2.FEC_REGISTRO_ALTA)=TRUNC(SYSDATE))
GROUP BY T2.CVE_ID_TRAMITE)
WHERE EXISTS(
SELECT 1 
FROM DIT_BIT_FLUJO_ARCH_MOVCICDA T2
WHERE T1.CVE_ID_TRAMITE=T2.CVE_ID_TRAMITE
AND (TRUNC(T2.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE) or TRUNC(T2.FEC_REGISTRO_ALTA)=TRUNC(SYSDATE))
GROUP BY T2.CVE_ID_TRAMITE)

