UPDATE DIT_BITACORA_PROC_MOVCI_CDA t1
SET REF_OBSERVACION =(
            select OBSERVACION
            from (
            select bit2.CVE_ID_CDA_SINDO_MOVCI, bit2.IDENTIF_ERROR||'|'||bit2.CVE_ID_CDA_MOVCI||'|'||res.DES_RESULTADO as OBSERVACION
            from DIT_BITACORA_PROC_MOVCI_CDA bit2, DIC_RESULTADO_CDA_SINDO res
            where (trunc(bit2.FEC_REGISTRO_ALTA) = trunc(sysdate) or trunc(bit2.FEC_REGISTRO_ACTUALIZADO) = trunc(sysdate))
            and bit2.IDENTIF_ERROR = res.CVE_ID_RESULTADO(+)
            and bit2.IDENTIF_ERROR <> '000'
            ) detalle
            where 1=1
            and detalle.CVE_ID_CDA_SINDO_MOVCI = t1.CVE_ID_CDA_SINDO_MOVCI)
where (trunc(t1.FEC_REGISTRO_ALTA) = trunc(sysdate) or trunc(T1.FEC_REGISTRO_ACTUALIZADO) = trunc(sysdate))
and t1.NUM_CONSEC_ORIG <> '000'
and exists (
            select bit2.rowid
            from DIT_BITACORA_PROC_MOVCI_CDA bit2, DIC_RESULTADO_CDA_SINDO res
            where (trunc(bit2.FEC_REGISTRO_ALTA) = trunc(sysdate) or trunc(bit2.FEC_REGISTRO_ACTUALIZADO) = trunc(sysdate))
            and bit2.IDENTIF_ERROR = res.CVE_ID_RESULTADO(+)
            and bit2.IDENTIF_ERROR <> '000'
            and bit2.CVE_ID_CDA_SINDO_MOVCI = t1.CVE_ID_CDA_SINDO_MOVCI
