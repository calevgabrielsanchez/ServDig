--- COMANDO: UPDATE_VALIDA_ESTADO

UPDATE DIT_BIT_FLUJO_ARCH_MOV06CDA T1
SET (T1.IND_VALIDA,T1.REF_ESTADO_SOLICITUD,T1.REF_ESTADO_TRAMITE) =
(
SELECT 
CASE WHEN SUM(IND_CIZ1+IND_CIZ2+IND_CIZ3+IND_CA+IND_HC) = 5 THEN 1
           WHEN SUM(IND_CIZ1+IND_CIZ2+IND_CIZ3+IND_HC) in (0,1,2,3) THEN 1
           WHEN SUM(IND_CIZ1+IND_CIZ2+IND_CIZ3)  =0 THEN 1
ELSE 0
END IND_VALIDA,
CASE WHEN SUM(IND_CIZ1+IND_CIZ2+IND_CIZ3+IND_CA+IND_HC) = 5 THEN 5
ELSE 5
END REF_ESTADO_SOLICITUD,
CASE WHEN SUM(IND_CIZ1+IND_CIZ2+IND_CIZ3+IND_CA+IND_HC) = 5 THEN 88
ELSE 85
END REF_ESTADO_TRAMITE
FROM DIT_BIT_FLUJO_ARCH_MOV06CDA T2
WHERE T1.CVE_ID_TRAMITE=T2.CVE_ID_TRAMITE
AND TRUNC(T2.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE)
GROUP BY T2.CVE_ID_TRAMITE)
WHERE EXISTS(
SELECT 1 
FROM DIT_BIT_FLUJO_ARCH_MOV06CDA T2
WHERE T1.CVE_ID_TRAMITE=T2.CVE_ID_TRAMITE
AND TRUNC(T2.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE)
GROUP BY T2.CVE_ID_TRAMITE)

--- COMANDO: DIT_MOV_ACLARACION_NSS_CDA 

UPDATE DIT_MOV_ACLARACION_NSS_CDA T1 SET (T1.CVE_ID_ESTADO_MOV_ENV_SINDO,T1.FEC_REGISTRO_ACTUALIZADO)=
(SELECT 
    CASE WHEN T2.REF_ESTADO_TRAMITE = '88' THEN 3  ELSE 2  END ,  SYSDATE
    FROM DIT_BIT_FLUJO_ARCH_MOV06CDA T2
    WHERE 1=1
      AND T1.CVE_ID_MOV_ACLARACION_NSS=T2.CVE_ID_TRAMITE
      AND T2.IND_VALIDA=1
      AND T1.CVE_ID_ESTADO_MOV_ENV_SINDO = 1
      AND TRUNC(T2.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE)
  )
WHERE EXISTS(SELECT 1 FROM DIT_BIT_FLUJO_ARCH_MOV06CDA T3
              WHERE 1=1
              AND T1.CVE_ID_MOV_ACLARACION_NSS=T3.CVE_ID_TRAMITE
              AND T3.IND_VALIDA=1
              AND T1.CVE_ID_ESTADO_MOV_ENV_SINDO = 1
            AND TRUNC(T3.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE))

