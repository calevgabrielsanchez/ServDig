(SELECT T2.CVE_ID_ESTADO_MOV_ENV_SINDO, T2.FEC_REGISTRO_ACTUALIZADO
    FROM DIT_MOV_ACLARACION_NSS_CDA T2
    WHERE 1=1
      AND T1.CVE_ID_DETALLE_NSS_CDA=T2.CVE_ID_DETALLE_NSS_CDA
      AND T2.CVE_ID_TIPO_NSS_ACLARACION IN (1,2)
      AND TRUNC(T2.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE)
      AND T2.CVE_ID_ESTADO_MOV_ENV_SINDO in(2,3)
  )
WHERE EXISTS(SELECT 1 FROM DIT_MOV_ACLARACION_NSS_CDA T3
             WHERE 1=1
             AND T1.CVE_ID_DETALLE_NSS_CDA=T3.CVE_ID_DETALLE_NSS_CDA
             AND T3.CVE_ID_TIPO_NSS_ACLARACION IN (1,2)
             AND TRUNC(T3.FEC_REGISTRO_ACTUALIZADO)=TRUNC(SYSDATE)
             AND T3.CVE_ID_ESTADO_MOV_ENV_SINDO in (2,3))
and T1.CVE_ID_ESTADO_MOV_ENV_SINDO = 1
