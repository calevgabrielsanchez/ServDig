        SUBSTR(CTAD.NSS,11,1) DVNSSDEST,                                            
        TO_CHAR(TO_DATE(CTAD.FEC_RECEPCION_MOV,'dd/mm/yyyy'),'DDMMYYYY') AS FECRECEPMOVDEST,
