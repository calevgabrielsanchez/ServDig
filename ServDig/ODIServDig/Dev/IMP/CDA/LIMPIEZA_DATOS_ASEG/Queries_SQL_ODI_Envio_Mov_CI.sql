        LPAD(CTAO.CVE_TIPO_INI_MOV, 2 ,'0') TIPMOVINIORIG,
        CTAO.CVE_INI_MOV AS ORIGMOVINIORIG, 
        --'0' AS ORIGMOVINIORIG,
        TO_CHAR(TO_DATE(CTAO.FEC_INI_MOV,'dd/mm/yyyy'),'DDMMYYYY') FECMOVINIORIG,
        LPAD(TRIM(replace( to_char(CTAO.SALARIO_BASE, '999999D99'), '.', '')),6, '0') AS SALBASEORIG,
        NVL(TRIM(CTAO.CVE_TIPO_SALARIO), '0') as TIPOSALORIG,
        NVL(TRIM(CTAO.CVE_EVENTUAL),0) AS TIPOTRABORIG,
        NVL(TRIM(CTAO.CVE_EXT_CONV_SUSP),0) AS EXTEMPORIG,
        NVL(TRIM(CTAO.CVE_SUBR_SERVICIOS),0) AS SUBROGSERVORIG,
        LPAD(CTAO.CVE_TIPO_FIN_MOV, 2, '0')  AS TIPOMOVFINORIG,
        CTAO.CVE_FIN_MOV  AS ORIGMOVFINORIG, 
        --'0' AS ORIGMOVFINORIG,
        CASE WHEN NVL(TO_CHAR(TO_DATE(CTAO.FEC_FIN_MOV,'dd/mm/yyyy'),'DDMMYYYY'), '00000000') = '31129999' THEN '00000000' ELSE 
            NVL(TO_CHAR(TO_DATE(CTAO.FEC_FIN_MOV,'dd/mm/yyyy'),'DDMMYYYY'), '00000000') END AS FEMOVFINORIG,
        NVL(TRIM(CTAO.CVE_JORNADA_SEMANAL),0) JORSEMORIG,
       CASE WHEN LPAD(CTAO.CVE_CONSEC_PERIODOS, 3, '0') is null THEN '000' else LPAD(CTAO.CVE_CONSEC_PERIODOS, 3, '0') end NUMCONSPERORIG,
        --LPAD(CTAO.CVE_CONSEC_PERIODOS, 3, '0') NUMCONSPERORIG,
        NVL(CTAO.CURP,'                  ') AS CURPORIG,
        SUBSTR(CTAD.CVE_REGISTRO_PATRONAL,1,8) AS REGPATDEST,                                           
        CTAD.CVE_MODALIDAD AS MODPATDEST,                                                   
       -- CIC.CVE_ID_MOV_CORRECCION AS TIPOOPERDEST,
