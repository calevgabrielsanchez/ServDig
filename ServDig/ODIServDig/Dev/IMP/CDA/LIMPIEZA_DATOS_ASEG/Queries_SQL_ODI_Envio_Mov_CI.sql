        NVL(TRIM(CTAD.CVE_EVENTUAL),0) AS TIPOTRABEVEDEST,
        NVL(TRIM(CTAD.CVE_EXT_CONV_SUSP),0) AS EXTEMPDEST,
        NVL(TRIM(CTAD.CVE_SUBR_SERVICIOS),0) AS SUBROGSERVDEST,
        LPAD(CTAD.CVE_TIPO_FIN_MOV, 2, '0')  AS TIPOMOVFINDEST,
        --'0' AS ORIMOVFINDEST,
        CTAD.CVE_FIN_MOV AS ORIMOVFINDEST,
        --TO_CHAR(TO_DATE(CTAD.FEC_FIN_MOV,'dd/mm/yyyy'),'DDMMYYYY') AS FECMOVFINDEST,
        CASE WHEN NVL(TO_CHAR(TO_DATE(CTAD.FEC_FIN_MOV,'dd/mm/yyyy'),'DDMMYYYY'), '00000000') = '31129999' THEN '00000000' ELSE 
            NVL(TO_CHAR(TO_DATE(CTAD.FEC_FIN_MOV,'dd/mm/yyyy'),'DDMMYYYY'), '00000000') END AS FECMOVFINDEST,
