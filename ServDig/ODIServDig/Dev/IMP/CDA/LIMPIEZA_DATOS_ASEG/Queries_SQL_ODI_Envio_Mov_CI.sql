            AND TRAM.CVE_ID_TIPO_TRAMITE = 139
            AND T.CVE_ID_ESTADO_TRAMITE in (75,37)
            AND ((MOVA.CVE_ID_TIPO_NSS_ACLARACION IN (1,2) OR MOVA.CVE_ID_TIPO_TRAM_CORREC_NSS IN(1,2,4))
              or (MOVA.CVE_ID_TIPO_NSS_ACLARACION =5 and  MOVA.CVE_ID_TIPO_TRAM_CORREC_NSS =8))
            AND (MOVA.CVE_ID_ESTADO_MOV_ENV_SINDO IS NULL or  MOVA.CVE_ID_ESTADO_MOV_ENV_SINDO != 3)
            AND NSS.CVE_ID_TIPO_NSS IN (1,2,3)
            AND mova.fec_registro_baja is null
            )
union
