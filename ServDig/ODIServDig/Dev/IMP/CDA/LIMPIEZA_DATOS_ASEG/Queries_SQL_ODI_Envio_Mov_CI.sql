       ,DELE.CVE_CIZ CIZ
       ,CTAD.IND_HISTORICO_CENTRAL 
FROM DIT_SOLICITUD S,
     DIT_TRAMITE T,
     DIT_CORRECCION_DATOS_ASEG DA,
     DIT_DETALLE_NSS_CDA NSS,
     DIT_CORRECCION_CTA_IND_CDA CIC,
     DIT_CTA_IND_NSS_CDA CTAO,
     DIT_CTA_IND_NSS_CDA CTAD,
     DIC_DELEGACION DELE,
     DIT_MOV_ACLARACION_NSS_CDA MOVA 
WHERE S.CVE_ID_SOLICITUD=T.CVE_ID_SOLICITUD
AND CTAO.CVE_DELEGACION_ORIGEN = DELE.CLAVE_DELEGACION
AND T.CVE_ID_TRAMITE=DA.CVE_ID_TRAMITE
AND DA.CVE_ID_CORRECCION_DATOS_ASEG=NSS.CVE_ID_CORRECCION_DATOS_ASEG
and CIC.CVE_ID_CTA_IND_OPER_ORIGEN = CTAO.CVE_ID_CTA_IND  
and CIC.CVE_ID_CTA_IND_OPER_DESTINO = CTAD.CVE_ID_CTA_IND 
AND MOVA.CVE_ID_DETALLE_NSS_CDA =  NSS.CVE_ID_DETALLE_NSS_CDA
and MOVA.CVE_ID_MOV_ACLARACION_NSS = CIC.CVE_ID_MOV_ACLARACION_NSS
--AND CTAO.CVE_ID_ORIGEN_PERIODO_CTA_IND =1
--AND CTAD.CVE_ID_ORIGEN_PERIODO_CTA_IND =2
AND S.CVE_ID_ESTADO_SOLICITUD = 5
AND S.CVE_ID_TIPO_SOLICITUD = 50
AND T.CVE_ID_ESTADO_TRAMITE in (75,37)
AND T.CVE_ID_TIPO_TRAMITE =139
AND MOVA.CVE_ID_TIPO_TRAM_CORREC_NSS IN (3,5,6,7)
AND mova.fec_registro_baja is null
AND CIC.fec_registro_baja is null
and cic.CVE_ID_CTA_IND_OPER_DESTINO is not null
AND (CIC.CVE_ID_ESTADO_MOV_ENV_SINDO IS NULL OR CIC.CVE_ID_ESTADO_MOV_ENV_SINDO = 2)
AND NOT EXISTS(
