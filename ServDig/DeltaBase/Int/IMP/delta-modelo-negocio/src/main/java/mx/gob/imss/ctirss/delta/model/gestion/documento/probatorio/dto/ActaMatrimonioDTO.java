package mx.gob.imss.ctirss.delta.model.gestion.documento.probatorio.dto;

public class ActaMatrimonioDTO {

	private String noActa;
	private String noFoja;
	private String noLibro;
	private String fechaSuceso;
	
	private String municipio;
	private String entidad;
	private String noJuzgado;
	
	
	/**
	 * @return the noActa
	 */
	public String getNoActa() {
		return noActa;
	}
	/**
	 * @param noActa the noActa to set
	 */
	public void setNoActa(String noActa) {
		this.noActa = noActa;
	}
	/**
	 * @return the noFoja
	 */
	public String getNoFoja() {
		return noFoja;
	}
	/**
	 * @param noFoja the noFoja to set
	 */
	public void setNoFoja(String noFoja) {
		this.noFoja = noFoja;
	}
	/**
	 * @return the noLibro
	 */
	public String getNoLibro() {
		return noLibro;
	}
	/**
	 * @param noLibro the noLibro to set
	 */
	public void setNoLibro(String noLibro) {
		this.noLibro = noLibro;
	}
	/**
	 * @return the fechaSuceso
	 */
	public String getFechaSuceso() {
		return fechaSuceso;
	}
	/**
	 * @param fechaSuceso the fechaSuceso to set
	 */
	public void setFechaSuceso(String fechaSuceso) {
		this.fechaSuceso = fechaSuceso;
	}
	/**
	 * @return the municipio
	 */
	public String getMunicipio() {
		return municipio;
	}
	/**
	 * @param municipio the municipio to set
	 */
	public void setMunicipio(String municipio) {
		this.municipio = municipio;
	}
	/**
	 * @return the entidad
	 */
	public String getEntidad() {
		return entidad;
	}
	/**
	 * @param entidad the entidad to set
	 */
	public void setEntidad(String entidad) {
		this.entidad = entidad;
	}
	/**
	 * @return the noJuzgado
	 */
	public String getNoJuzgado() {
		return noJuzgado;
	}
	/**
	 * @param noJuzgado the noJuzgado to set
	 */
	public void setNoJuzgado(String noJuzgado) {
		this.noJuzgado = noJuzgado;
	}
	}
